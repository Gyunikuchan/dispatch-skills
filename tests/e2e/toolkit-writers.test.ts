import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { describe, it } from 'node:test';
import { toolkitRepo, planSource } from './helpers/toolkit-repo.ts';
import { appendRecord, foldLedger } from '../../skills/dispatch/scripts/toolkit/ledger.ts';
const records = (r: Awaited<ReturnType<typeof toolkitRepo>>) => foldLedger(r.session).records.filter(x=>x.kind==='writer');
const launchPath = (r: Awaited<ReturnType<typeof toolkitRepo>>) => path.resolve(r.session,records(r).findLast(x=>x.data['phase']==='launched')!.data['path']);
const crash = (point: string) => (p: string) => { if(p===point) throw new Error('crash'); };
describe('toolkit writer worktrees', () => {
  it('creates records, refuses duplicate work, restores missing paths and uses fresh abandoned paths', async t => {
    const r=await toolkitRepo(); t.after(r.cleanup);
    for(const args of [['worktree','create','T1','--relaunch'],['worktree','abandon','T1','--reason','stop']]) {
      assert.equal((await r.run(args)).output.reason,'no-open-launch');
      assert.equal(records(r).length,0);
      assert.equal(fs.existsSync(r.integration),false);
    }
    assert.equal((await r.run(['worktree','create','T1'])).exit,0);
    const cwd=launchPath(r); const base=r.git(['rev-parse','HEAD'],cwd);
    assert.equal(base,r.git(['rev-parse','HEAD'],r.integration));
    assert.equal((await r.run(['worktree','create','T1'])).output.reason,'writer-open');
    fs.rmSync(cwd,{recursive:true,force:true});
    assert.equal((await r.run(['worktree','create','T1'])).exit,0);
    assert.equal(records(r).length,1);
    assert.equal(r.git(['rev-parse','HEAD'],cwd),base);
    assert.equal((await r.run(['worktree','submit','T1'])).output.reason,'no-changes');
    fs.writeFileSync(path.join(cwd,'src/file.ts'),'changed\n');
    assert.equal((await r.run(['worktree','create','T1','--relaunch'])).exit,0);
    assert.equal(launchPath(r),cwd); assert.equal(records(r).length,2);
    assert.equal(records(r)[1]!.data['base'].commit,base);
    assert.equal(fs.readFileSync(path.join(cwd,'src/file.ts'),'utf8'),'changed\n');
    fs.writeFileSync(path.join(cwd,'extra'),'untracked');
    assert.equal((await r.run(['worktree','abandon','T1','--reason','stop'])).exit,0);
    const ref='refs/dispatch/test/abandoned/T1-2';
    assert.equal(r.git(['show',ref+':extra']),'untracked');
    assert.equal(r.git(['show',ref+':src/file.ts']),'changed');
    assert.equal(r.git(['rev-parse','HEAD'],cwd),base);
    assert.equal(fs.readFileSync(path.join(cwd,'extra'),'utf8'),'untracked');
    assert.equal((await r.run(['worktree','create','T1'])).exit,0);
    assert.notEqual(launchPath(r),cwd);
  });
  it('adopts only the predicted crash worktree despite other ledger records and launches', async t => {
    const source=planSource.replace('| T1 | File | Works | none | SC1 |','| T1 | File | Works | none | SC1 |\n| T2 | Other | Works | none | SC2 |').replace('## Success Criteria','### T2 — Other\n#### [MODIFY] other\n- Purpose: other.\n\n## Success Criteria').replace('## Verification Plan','- [SC2] Other works\n  - Changes: other\n  - Verify: `node -e "process.exit(0)"`\n  - Evidence: verify\n\n## Verification Plan');
    const r=await toolkitRepo(source); t.after(r.cleanup);
    assert.equal((await r.run(['worktree','create','T1'])).exit,0);
    assert.equal((await r.run(['worktree','abandon','T1','--reason','stop'])).exit,0);
    const interrupted=await r.run(['worktree','create','T1'],crash('create:after-add'));
    assert.equal(interrupted.exit,2,JSON.stringify(interrupted)); assert.equal(interrupted.value.message,'crash',JSON.stringify(interrupted));
    const predicted=path.join(r.session,'.state/worktrees/T1-2');
    const head=r.git(['rev-parse','HEAD'],predicted);
    await appendRecord(r.session,{kind:'note',by:'orchestrator',key:'intervening',data:{text:'intervening'}},r.deps);
    assert.equal((await r.run(['worktree','create','T2'])).exit,0);
    assert.equal((await r.run(['worktree','create','T1'])).exit,0);
    assert.equal(launchPath(r),predicted);
    assert.equal(records(r).filter(x=>x.data['path']==='.state/worktrees/T1-2').length,1);
    assert.equal(records(r).at(-1)!.data['base'].commit,head);
  });
  it('submits modifications additions deletions and untracked files within ownership', async t => {
    const source=planSource.replace('#### [MODIFY] src/file.ts','#### [MODIFY] src/file.ts\n- Purpose: file.\n#### [NEW] src/add.ts\n- Purpose: addition.\n#### [DELETE] src/delete.ts\n- Purpose: deletion.\n#### [NEW] src/untracked.ts');
    const r=await toolkitRepo(source); t.after(r.cleanup);
    fs.writeFileSync(path.join(r.root,'src/delete.ts'),'delete'); r.git(['add','.']); r.git(['commit','-m','fixture']);
    assert.equal((await r.run(['worktree','create','T1'])).exit,0); const cwd=launchPath(r);
    fs.writeFileSync(path.join(cwd,'src/file.ts'),'changed'); fs.writeFileSync(path.join(cwd,'src/add.ts'),'added'); r.git(['add','src/add.ts'],cwd);
    fs.unlinkSync(path.join(cwd,'src/delete.ts')); fs.writeFileSync(path.join(cwd,'src/untracked.ts'),'new');
    const interrupted=await r.run(['worktree','submit','T1'],crash('submit:after-commit'));
    assert.equal(interrupted.exit,2,JSON.stringify(interrupted)); assert.equal(interrupted.value.message,'crash',JSON.stringify(interrupted));
    const committed=r.git(['rev-parse','HEAD'],cwd);
    assert.equal((await r.run(['worktree','submit','T1'])).exit,0);
    assert.equal(r.git(['rev-parse','HEAD'],cwd),committed);
    const finished=records(r).at(-1)!;
    assert.equal(finished.data['phase'],'finished');
    assert.equal(r.git(['rev-parse','refs/dispatch/test/candidates/T1-1']),finished.data['candidate']);
    assert.equal(r.git(['show','HEAD:src/untracked.ts'],cwd),'new');
    assert.equal(r.git(['status','--porcelain'],cwd),'');
    assert.equal((await r.run(['worktree','create','T1'])).output.reason,'candidate-pending');
  });
  it('refuses out of scope changes before committing and recovers committed submissions', async t => {
    const r=await toolkitRepo(); t.after(r.cleanup);
    assert.equal((await r.run(['worktree','create','T1'])).exit,0); const cwd=launchPath(r); const base=r.git(['rev-parse','HEAD'],cwd);
    fs.writeFileSync(path.join(cwd,'outside'),'outside');
    const refused=await r.run(['worktree','submit','T1']); assert.equal(refused.output.reason,'out-of-scope',JSON.stringify(refused)); assert.ok(JSON.stringify(refused.value).includes('outside'),JSON.stringify(refused));
    assert.equal(r.git(['rev-parse','HEAD'],cwd),base); fs.unlinkSync(path.join(cwd,'outside'));
    fs.writeFileSync(path.join(cwd,'src/file.ts'),'submitted');
    const interrupted=await r.run(['worktree','submit','T1'],p=>{if(p==='submit:after-commit'){fs.writeFileSync(path.join(cwd,'src/file.ts'),'later');throw new Error('crash');}});
    assert.equal(interrupted.exit,2,JSON.stringify(interrupted)); assert.equal(interrupted.value.message,'crash',JSON.stringify(interrupted));
    const committed=r.git(['rev-parse','HEAD'],cwd);
    const relaunched=await r.run(['worktree','create','T1','--relaunch']); assert.equal(relaunched.output.reason,'submit-pending',JSON.stringify(relaunched));
    const abandoned=await r.run(['worktree','abandon','T1','--reason','stop']); assert.equal(abandoned.output.reason,'submit-pending',JSON.stringify(abandoned));
    const recovered=await r.run(['worktree','submit','T1']); assert.equal(recovered.exit,0,JSON.stringify(recovered));
    assert.equal(r.git(['rev-parse','HEAD'],cwd),committed); assert.equal(records(r).at(-1)!.data['candidate'],committed);
    assert.equal(fs.readFileSync(path.join(cwd,'src/file.ts'),'utf8'),'later');
    assert.notEqual(r.git(['status','--porcelain'],cwd),'');
  });
  it('soft resets an unrecorded submit whose committed diff exceeds ownership', async t => {
    const r=await toolkitRepo(); t.after(r.cleanup); await r.run(['worktree','create','T1']); const cwd=launchPath(r); const base=r.git(['rev-parse','HEAD'],cwd);
    fs.writeFileSync(path.join(cwd,'src/file.ts'),'submitted');
    const interrupted=await r.run(['worktree','submit','T1'],crash('submit:after-commit'));
    assert.equal(interrupted.exit,2,JSON.stringify(interrupted)); assert.equal(interrupted.value.message,'crash',JSON.stringify(interrupted));
    fs.writeFileSync(path.join(cwd,'outside'),'outside'); r.git(['add','outside'],cwd); r.git(['commit','--amend','--no-edit'],cwd);
    assert.equal((await r.run(['worktree','submit','T1'])).output.reason,'out-of-scope');
    assert.equal(r.git(['rev-parse','HEAD'],cwd),base); assert.equal(fs.readFileSync(path.join(cwd,'outside'),'utf8'),'outside');
    assert.equal(records(r).filter(x=>x.data['phase']==='finished').length,0);
  });
});
